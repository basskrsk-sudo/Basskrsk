'use strict';
// Diagnostic-only SQLite writes: never run them in the HTTP/payment event loop.
// A single background worker commits coalesced events and the latest heartbeat.
// No customer data, SQL text, logs or payment identifiers cross threads.
const path = require('node:path');
const { Worker } = require('node:worker_threads');

const MAX_PENDING_EVENTS = 64;
const WRITE_TIMEOUT_MS = 15000;
const FAILURE_BACKOFF_MS = 5 * 60 * 1000;
function createHealthWriteQueue({
  source,
  WorkerClass = Worker,
  workerPath = path.join(__dirname, 'health-write-worker.js'),
  debounceMs = 200,
  timeoutMs = WRITE_TIMEOUT_MS,
  failureBackoffMs = FAILURE_BACKOFF_MS,
  onError = error => console.warn('[health] delayed diagnostic writes:', error.message),
} = {}) {
  if (typeof source !== 'string' || !source)
    throw new TypeError('SQLite database path is required');
  let events = [];
  let heartbeat = null;
  let prune = false;
  let timer = null;
  let active = null;
  let retryAfter = 0;
  const hasPending = () => !!(events.length || heartbeat || prune);
  function schedule() {
    if (timer || active || !hasPending()) return;
    const delay = Math.max(debounceMs, retryAfter - Date.now());
    timer = setTimeout(() => {
      timer = null;
      void flush().catch(onError);
    }, delay);
    timer.unref?.();
  }
  function appendEvent(type, severity, detail) {
    // All arguments are already bounded and generated by the health watcher.
    events.push({ type, severity, detail, at: new Date().toISOString() });
    if (events.length > MAX_PENDING_EVENTS) events.shift();
    schedule();
  }
  function updateHeartbeat(at, bootId) {
    // Coalesce faster requests: only the newest timestamp should hit disk.
    heartbeat = {at, bootId};
    schedule();
  }
  function pruneOldEvents() {
    prune = true;
    schedule();
  }
  function runBatch(batch) {
    return new Promise((resolve, reject) => {
      let worker;
      try {
        worker = new WorkerClass(workerPath, {
          workerData: { source, ...batch },
          resourceLimits: { maxOldGenerationSizeMb: 32 },
        });
        worker.unref?.(); // A diagnostic worker must not hold up shutdown.
      } catch (error) { reject(error); return; }
      let settled = false;
      const finish = error => {
        if (settled) return;
        settled = true;
        clearTimeout(timeout);
        if (error) reject(error);
        else resolve();
      };
      const timeout = setTimeout(() => {
        Promise.resolve(worker.terminate()).then(
          () => finish(new Error('SQLite diagnostic write timed out')),
          () => finish(new Error('SQLite diagnostic worker termination failed'))
        );
      }, timeoutMs);
      timeout.unref?.();
      worker.once('message', message => {
        if (message?.ok === true) finish();
        else finish(new Error('SQLite diagnostic worker failed: ' +
          String(message?.code || 'unknown').slice(0,40)));
      });
      worker.once('error', finish);
      worker.once('exit', code => {
        if (!settled) finish(new Error('SQLite diagnostic worker exited: ' + code));
      });
    });
  }
  async function flush() {
    if (timer) { clearTimeout(timer); timer = null; }
    if (active) { await active; return flush(); }
    if (!hasPending()) return;
    const delay = retryAfter - Date.now();
    if (delay > 0) {
      schedule();
      return;
    }
    const batch = { events, heartbeat, prune };
    events = []; heartbeat = null; prune = false;
    active = runBatch(batch).catch(error => {
      // Reporting is best-effort, but retain bounded diagnostics for retry.
      // This avoids generating more I/O every minute while /data is degraded.
      events = batch.events.concat(events).slice(-MAX_PENDING_EVENTS);
      if (!heartbeat) heartbeat = batch.heartbeat;
      prune = prune || batch.prune;
      retryAfter = Date.now() + failureBackoffMs;
      onError(error);
    }).finally(() => {
      active = null;
      schedule();
    });
    await active;
  }
  return { appendEvent, updateHeartbeat, pruneOldEvents, flush };
}
module.exports = {
  createHealthWriteQueue, MAX_PENDING_EVENTS,
  FAILURE_BACKOFF_MS,
};
